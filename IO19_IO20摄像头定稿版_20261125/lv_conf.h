//   本机 sdkconfig 实测: CONFIG_SPIRAM_USE_MALLOC=y, CONFIG_SPIRAM_MALLOC_ALWAYSINTERNAL=4096
//   → 规则是"malloc 尺寸 <= 4096 字节一律走内部 RAM, > 4096 才走 PSRAM"。
//   LVGL 用它算每层每块的行数: lv_refr.c:1046
//      max_rgb_row_height = LV_DRAW_LAYER_SIMPLE_BUF_SIZE / w / px_size
//   240 宽 RGB565 → 24576/240/2 = 51 行/块 → 24480 字节 > 4096 → 走 PSRAM(正确)
//   ★ 我曾把它改成 4096: 4096/240/2 = 8 行 → 3840 字节 <= 4096 → 全部落进内部 RAM,
//     结果每帧都从只有 33KB 的内部 RAM 里申请 3.8KB 并释放, 直接导致
//       E esp-aes: Failed to allocate memory → websocket TLS 读失败 → 语音掉线。
//     这是"改了反而更糟"的典型案例, 不要低于 8192。
